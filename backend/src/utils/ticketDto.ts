export function toAuthorTicket<T extends Record<string, unknown>>(ticket: T) {
  const {
    id,
    ticketNumber,
    authorId: _authorId,
    bookId,
    subject,
    description,
    status,
    category,
    priority,
    createdAt,
    updatedAt,
    resolvedAt,
  } = ticket;
  return {
    id,
    ticketNumber,
    bookId,
    subject,
    description,
    status,
    category,
    priority,
    createdAt,
    updatedAt,
    resolvedAt,
  };
}

